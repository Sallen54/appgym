/*
 * La versión sale de la etiqueta de git cuando compila GitHub Actions
 * (APP_VERSION_NAME / APP_VERSION_CODE). En local usa los valores de abajo.
 */
val versionNameProp = System.getenv("APP_VERSION_NAME") ?: "1.0"
val versionCodeProp = (System.getenv("APP_VERSION_CODE") ?: "1").toInt()

/*
 * Firma de release. Si existe keystore.properties (en local) o las variables de
 * entorno (en CI), el APK se firma con esa clave. Si no, se compila sin firmar.
 */
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) load(keystorePropertiesFile.inputStream())
}
val storeFilePath: String? = keystoreProperties.getProperty("storeFile")
    ?: System.getenv("KEYSTORE_PATH")
val hayFirma = storeFilePath != null && file(storeFilePath).exists()

android {
    namespace = "com.alejandro.appgym"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.alejandro.appgym"
        minSdk = 26
        targetSdk = 35
        versionCode = versionCodeProp
        versionName = versionNameProp
        vectorDrawables { useSupportLibrary = true }
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (hayFirma) {
            create("release") {
                storeFile = file(storeFilePath!!)
                storePassword = keystoreProperties.getProperty("storePassword")
                    ?: System.getenv("KEYSTORE_PASSWORD")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                    ?: System.getenv("KEY_ALIAS")
                keyPassword = keystoreProperties.getProperty("keyPassword")
                    ?: System.getenv("KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (hayFirma) signingConfig = signingConfigs.getByName("release")
        }
    }


    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }

    buildFeatures { compose = true }

    packaging {
        resources { excludes += "/META-INF/{AL2.0,LGPL2.1}" }
    }
}

